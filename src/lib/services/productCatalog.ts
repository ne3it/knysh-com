/** Названия групп приводятся к названиям из ТЗ панели */
const GROUP_LABELS: Record<string, string> = {
  'Другие товары по 713': 'Другие категории и франшизы',
  'УНИВЕРСАЛЬНЫЙ ВВОД': 'Другой товар (лимит вручную)',
};

function toCatalogItem(category: PriceControlCategory): ProductCatalogItem {
  const limitPercent = limitToPercent(category.limit);
  const name = PANEL_LABELS[category.name] ?? category.name;
  // У ручного ввода лимита своя подпись: «(лимит: 30%)» там было бы ложью
  const label =
    category.id === PRICE_CONTROL_CUSTOM_ID ? name : `${name} (лимит: ${limitPercent}%)`;
  return { id: category.id, label, limitPercent };
}

function buildCatalogGroups(): ProductCatalogGroup[] {
  return PRICE_CONTROL_GROUPS.map(({ group, categories }) => {
    const items = categories.map(toCatalogItem);
    if (group === 'Другие товары по 713') items.push(PVZ_CATALOG_ITEM);

    const percents = categories.map((category) => limitToPercent(category.limit));
    const min = Math.min(...percents);
    const max = Math.max(...percents);
    const range = min === max ? `${max}%` : `${min}-${max}%`;
    const label = `${GROUP_LABELS[group] ?? group} (Пост. 713 — ${range})`;

    return { label, items };
  });
}

/** Каталог панели: <optgroup> по товарным секторам 713 + франшиза ПВЗ */
export const PRODUCT_CATALOG_GROUPS: ProductCatalogGroup[] = buildCatalogGroups();

/** Плоский список позиций каталога — для поиска по id */
export const PRODUCT_CATALOG_ITEMS: ProductCatalogItem[] = PRODUCT_CATALOG_GROUPS.flatMap(
  (group) => group.items
);

/** Товар по умолчанию — первая позиция справочника 713 */
export const DEFAULT_CATALOG_ITEM_ID: string = ALL_PRICE_CONTROL_CATEGORIES[0].id;

/** Позиция каталога по id (undefined, если id неизвестен) */
export function getCatalogItem(id: string | undefined): ProductCatalogItem | undefined {
  if (!id) return undefined;
  return PRODUCT_CATALOG_ITEMS.find((item) => item.id === id);
}

/** Выбрана ли франшиза ПВЗ */
export function isPvzFranchise(id: string | undefined): boolean {
  return id === GLOBAL_PVZ_CATEGORY_ID;
}

/**
 * Мосты «справочник инструмента → каталог панели».
 *
 * У инструментов с собственной таксономией (сплит-калькулятор и планировщик старта)
 * категории описаны своими id, поэтому здесь они сопоставлены с позициями 713 по
 * названию из справочника. Позиции без соответствия (например, электроника, которой
 * в Постановлении № 713 нет) намеренно не сопоставлены — выбор в панели тогда не меняется.
 */
const CATEGORY_NAME = new Map(
  ALL_PRICE_CONTROL_CATEGORIES.map((category) => [category.name, category.id])
);

function buildBridge(names: Record<string, string>): Record<string, string> {
  return Object.entries(names).reduce<Record<string, string>>((acc, [localId, catalogName]) => {
    const catalogId = CATEGORY_NAME.get(catalogName);
    if (catalogId) acc[localId] = catalogId;
    return acc;
  }, {});
}

