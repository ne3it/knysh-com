/**
 * Инверсия мостов: позиция каталога панели → локальная категория инструмента.
 * Обратное направление нужно, чтобы смена категории в форме тут же двигала
 * главный селект панели. Названия, которые сопоставлены с несколькими
 * категориями инструмента, в мосты намеренно не попадают — иначе выбор в
 * панели уводил бы форму в чужую категорию.
 */
function invertBridge(bridge: Record<string, string>): Record<string, string> {
  const counts = Object.values(bridge).reduce<Record<string, number>>((acc, id) => {
    acc[id] = (acc[id] ?? 0) + 1;
    return acc;
  }, {});
  return Object.entries(bridge).reduce<Record<string, string>>((acc, [localId, catalogId]) => {
    if (counts[catalogId] === 1) acc[catalogId] = localId;
    return acc;
  }, {});
}

