/**
 * ПЛОЩАДЬ СЕЧЕНИЯ СТОЙКИ, м² — из неё считается объём пиломатериала.
 *
 * Считается из размеров, а не хранится числом: при добавлении типоразмера
 * объём посчитается сам, и ошибка «150×150 вместо 50×150» станет
 * невозможной.
 */
export function studCrossSectionM2(size: Pick<StudSize, 'thicknessMm' | 'depthMm'>): number {
  return (size.thicknessMm * size.depthMm) / 1e6;
}

/** Объём сечения обвязки, м² — брус 150×150 и 200×200 */
export function beamCrossSectionM2(beamMm: number): number {
  return (beamMm * beamMm) / 1e6;
}

